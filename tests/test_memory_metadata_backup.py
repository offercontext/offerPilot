from contextlib import closing
from hashlib import sha256
import json
import sqlite3
import subprocess
import sys
from zipfile import ZipFile

import pytest

from offerpilot.backup_archive import MANIFEST, stage_archive, workspace_files
from offerpilot.backup_export import export_archive
from offerpilot import backup_restore as restore
from tests.test_backup_install import cold


def predecessor(tmp_path):
    root = tmp_path / "live"
    subprocess.run([sys.executable, "-c", "from pathlib import Path; from offerpilot.db import init_database; "
                    f"s=init_database(Path({str(root / 'data.db')!r})); s.kw['bind'].dispose()"], check=True)
    archive = tmp_path / "new.zip"
    archive.write_bytes(export_archive(root, '{}'))
    extracted = tmp_path / "old"
    with ZipFile(archive) as zipped:
        zipped.extractall(extracted)  # trusted test-owned archive
    with closing(sqlite3.connect(extracted / "data.db")) as db:
        db.execute("DROP TABLE confirmed_memory_version_metadata")
        db.execute("DELETE FROM schema_migrations WHERE version='0040_confirmed_memory_metadata'")
        db.execute("INSERT INTO confirmed_memories VALUES ('legacy-memory',2,'active')")
        db.execute("INSERT INTO confirmed_memory_versions VALUES ('legacy-v1','legacy-memory',1,'旧内容','2000-01-01T00:00:00+00:00')")
        db.execute("INSERT INTO confirmed_memory_versions VALUES ('legacy-v2','legacy-memory',2,'新内容','2001-01-01T00:00:00+00:00')")
        payload = {"mutation_id": "22222222-2222-4222-8222-222222222222", "action": "confirm",
                   "expected_version": 0, "confirmed": True, "content": "旧内容", "memory_id": None}
        fingerprint = sha256(json.dumps(payload, sort_keys=True, ensure_ascii=False).encode()).hexdigest()
        db.execute("INSERT INTO confirmed_memory_mutations VALUES (?,?,?,?)", (payload["mutation_id"], 'legacy-memory', fingerprint, 1))
        db.commit()
        schema = db.execute("SELECT type,name,tbl_name,sql FROM sqlite_master WHERE name NOT LIKE 'sqlite_%' ORDER BY type,name").fetchall()
        # Independently generated by init_database at actual base commit 08d5bc85.
        assert sha256(json.dumps(schema).encode()).hexdigest() == "0466200dacc065c3617fcb61c774636787555bef50d17d027bf37956339233e1"
    return root, extracted


def pack(extracted, archive):
    manifest = json.loads((extracted / MANIFEST).read_text())
    manifest["files"] = {k: v for k, v in workspace_files(extracted).items() if k != MANIFEST}
    (extracted / MANIFEST).write_text(json.dumps(manifest))
    with ZipFile(archive, "w") as zipped:
        for path in extracted.rglob('*'):
            if path.is_file():
                zipped.write(path, path.relative_to(extracted).as_posix())


def test_predecessor_private_upgrade_and_cold_install(tmp_path):
    root, extracted = predecessor(tmp_path)
    archive = tmp_path / "old.zip"
    pack(extracted, archive)
    original_archive = archive.read_bytes()
    before = workspace_files(root)
    restore.prepare(root, archive)
    record = restore.read_record(root)
    candidate, _, _ = restore.operation_paths(root, record)
    assert workspace_files(root) == before
    assert archive.read_bytes() == original_archive
    assert record["schema_upgrade"] == "memory_metadata_v1"
    assert record["files"] == workspace_files(candidate)
    manifest = json.loads((candidate / MANIFEST).read_text())
    assert manifest["files"] == {k: v for k, v in record["files"].items() if k != MANIFEST}
    restore.confirm(root, record["id"], record["sha256"], "REPLACE WORKSPACE")
    result = cold(root)
    assert result.returncode == 0, result.stderr
    assert restore.status(root)["state"] == "completed"
    assert archive.read_bytes() == original_archive
    code = ("from pathlib import Path; from offerpilot.db import init_database; "
            "from offerpilot.confirmed_memory.repository import ConfirmedMemoryRepository,MemoryMutation; "
            f"s=init_database(Path({str(root / 'data.db')!r})); r=ConfirmedMemoryRepository(s); "
            "v=r.get('legacy-memory'); assert len(v['versions'])==2; "
            "assert v['metadata']['category']=='unclassified'; "
            "x=r.mutate(None,MemoryMutation(mutation_id='22222222-2222-4222-8222-222222222222',action='confirm',"
            "expected_version=0,confirmed=True,content='旧内容')); assert x['content']=='新内容'; "
            "s.kw['bind'].dispose()")
    replay = subprocess.run([sys.executable, "-c", code], capture_output=True, text=True, timeout=30)
    assert replay.returncode == 0, replay.stderr


@pytest.mark.parametrize("sql", ["CREATE TABLE injected (id TEXT)", "CREATE TRIGGER injected AFTER INSERT ON confirmed_memories BEGIN DELETE FROM confirmed_memories; END"])
def test_predecessor_extra_schema_rejected_without_changes(tmp_path, sql):
    root, extracted = predecessor(tmp_path)
    with closing(sqlite3.connect(extracted / "data.db")) as db:
        db.execute(sql)
        db.commit()
    archive = tmp_path / "bad.zip"
    pack(extracted, archive)
    original_archive, before = archive.read_bytes(), workspace_files(root)
    candidate = tmp_path / "candidate"
    with pytest.raises(ValueError, match="archive_schema_mismatch"):
        stage_archive(archive, candidate, root / "data.db")
    assert not candidate.exists()
    assert workspace_files(root) == before and archive.read_bytes() == original_archive


@pytest.mark.parametrize("outcome", ["tamper", "rollback"])
def test_upgraded_stage_tamper_and_incomplete_startup_preserve_original(tmp_path, outcome):
    root, extracted = predecessor(tmp_path)
    archive = tmp_path / "old.zip"
    pack(extracted, archive)
    original_archive, before = archive.read_bytes(), workspace_files(root)
    record = restore.prepare(root, archive)
    restore.confirm(root, record["id"], record["sha256"], "REPLACE WORKSPACE")
    candidate, _, _ = restore.operation_paths(root, record)
    if outcome == "tamper":
        with closing(sqlite3.connect(candidate / "data.db")) as db:
            db.execute("UPDATE confirmed_memory_versions SET content='tampered'")
            db.commit()
        assert cold(root).returncode != 0
        assert restore.status(root)["state"] == "failed"
    else:
        assert cold(root, complete=False).returncode == 0
        assert restore.status(root)["state"] == "installed"
        assert cold(root).returncode == 0
        assert restore.status(root)["state"] == "rolled_back"
    assert workspace_files(root) == before
    assert archive.read_bytes() == original_archive


def test_current_metadata_archive_roundtrip_does_not_upgrade(tmp_path):
    root = tmp_path / "live"
    code = ("from pathlib import Path; from offerpilot.db import init_database; "
            "from offerpilot.confirmed_memory.repository import ConfirmedMemoryRepository,MemoryMutation; "
            f"s=init_database(Path({str(root / 'data.db')!r})); "
            "ConfirmedMemoryRepository(s).mutate(None,MemoryMutation(mutation_id='22222222-2222-4222-8222-222222222222',"
            "action='confirm',expected_version=0,confirmed=True,content='dated goal',"
            "metadata={'category':'goal','valid_until':'2030-01-01T00:00:00Z'})); s.kw['bind'].dispose()")
    subprocess.run([sys.executable, "-c", code], check=True, timeout=30)
    archive = tmp_path / "current.zip"
    archive.write_bytes(export_archive(root, '{}'))
    candidate = tmp_path / "candidate"
    record = stage_archive(archive, candidate, root / "data.db")
    assert record["schema_upgrade"] is None
    with closing(sqlite3.connect(candidate / "data.db")) as db:
        assert db.execute("SELECT category,valid_until FROM confirmed_memory_version_metadata").fetchall() == [("goal", "2030-01-01T00:00:00+00:00")]
